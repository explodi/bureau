/**
 * Compiles the Vulkan backend's GLSL to the SPIR-V it embeds, committed so that a
 * game builds it with no shader compiler. Run after changing a shader:
 *
 *   deno run --allow-read --allow-write --allow-env --allow-sys tools/vulkan_shaders.ts
 */
// Run so rarely that its compiler stays out of everyone's lockfile.
// deno-lint-ignore no-import-prefix
import glslangModule from "npm:@webgpu/glslang@0.0.15/dist/node-devel/glslang.js";

const FOLDER = new URL("../src/backends/vulkan_shaders/", import.meta.url);
const OUTPUT = new URL("../src/backends/vulkan_shaders.inc", import.meta.url);

interface Glslang {
  compileGLSL(source: string, stage: string, debug: boolean): Uint32Array;
  then?: unknown;
}

// The compiler's module has a `then` that answers itself, so awaiting it never ends.
const glslang = await new Promise<Glslang>((resolve) => {
  const load = glslangModule as unknown as () => {
    then(ready: (module: Glslang) => void): void;
  };
  load().then((module) => {
    delete module.then;
    resolve(module);
  });
});

function words(name: string, spirv: Uint32Array): string {
  const rows: string[] = [];
  for (let at = 0; at < spirv.length; at += 8) {
    const row = [...spirv.subarray(at, at + 8)]
      .map((word) => `0x${word.toString(16).padStart(8, "0")}`)
      .join(", ");
    rows.push(`    ${row},`);
  }
  return `const std::uint32_t ${name}[] = {\n${rows.join("\n")}\n};\n`;
}

async function compile(file: string, stage: string): Promise<Uint32Array> {
  const source = await Deno.readTextFile(new URL(file, FOLDER));
  return glslang.compileGLSL(source, stage, false);
}

const vertex = await compile("ui.vert", "vertex");
const fragment = await compile("ui.frag", "fragment");
await Deno.writeTextFile(
  OUTPUT,
  "// Generated by tools/vulkan_shaders.ts from vulkan_shaders/.\n" +
    words("kVertexShader", vertex) + words("kFragmentShader", fragment),
);
